/* מפגשים שהגיעו מהשרת (meet.state) — במבט של מקצוע אחד מורידים את מפגשי
   המקצוע האחר. מפגש בלי מקצוע (לא מהתוכנית) נשאר בשני המבטים. */
window.TS_scopeMeetings = function (slug, list) {
  const v = window.TS_GUIDE_VIEW;
  if (!v || v.slug !== slug || !Array.isArray(list)) return list;
  return list.filter(m => { const s = window.TS_meetingSubject(slug, m.date); return !s || s === v.subject; });
};

/* מקצוע המפגש שחל בתאריך הזה (רבקה) — או '' כשהמפגש לכל מורי המדריכ/ה.
   קורא את התוכנית המלאה, לא המסוננת — אחרת מפגש של המקצוע האחר היה נראה "לכולם". */
window.TS_meetingSubject = function (slug, date) {
  const plan = (window.TS_PLANS && window.TS_PLANS[slug]) || null;
  if (!plan || !plan.meetings) return '';
  const m = plan.meetings.find(x => (x.dates || [x.date, x.date2]).indexOf(date) !== -1);
  return (m && m.subject) || '';
};

/* המפגש הקרוב ביותר שטרם התקיים (כולל היום) — או null אם השנה הסתיימה */
window.TS_nextMeeting = function (plan) {
  if (!plan || !plan.meetings) return null;
  const today = new Date();
  const iso = today.getFullYear() + '-' +
    String(today.getMonth() + 1).padStart(2, '0') + '-' +
    String(today.getDate()).padStart(2, '0');
  // מפגש בשני ימים (שירה) נשאר "הבא" עד שעבר גם המועד השני
  return plan.meetings.find(m => (m.date2 || m.date) >= iso) || null;
};

/* כל מועדי ההתחלה של מפגש: [{ date, start, part }] — תאריך ISO, שעת התחלה HH:MM,
   ותווית המועד (תוכנית/בוקר/ערב). משמש את תזכורת המייל שהשרת שולח למיטל בתחילת
   כל מפגש (code.gs → meetRemindTick) — השרת טוען את הקובץ הזה ולא מחזיק לוח משלו.
   הפורמטים שבקובץ:
     · time עם תאריך לכל מועד — "בוקר 22.9 · 14:00–15:30 · ערב 23.9 · 20:00–21:30" (שירה, שרה)
     · goal עם שעה לכל תוכנית — "70% חיצוני (ג׳ 13.10 בשעה 16:00, …): …" (מוריה)
     · time בלי תאריך — כל שעת התחלה ביום date: "11:00 / 18:00", "9:00–10:00 · 17:00–18:00" */
window.TS_meetingSlots = function (m) {
  if (!m || !m.date) return [];
  // מפגש שמועד בו הוזז (TS_applyPlanChanges) — המועדים כבר מחושבים
  if (Array.isArray(m.slots)) return m.slots.map(s => Object.assign({}, s));
  const days = (m.dates && m.dates.length) ? m.dates : [m.date, m.date2].filter(Boolean);
  const pad = t => (t.length === 4 ? '0' : '') + t;
  const isoOf = (d, mo) => days.find(x => +x.slice(8, 10) === +d && +x.slice(5, 7) === +mo) || '';
  const out = [];
  const add = (date, start, part, end) => {
    if (date && start && !out.some(s => s.date === date && s.start === pad(start))) {
      const o = { date: date, start: pad(start), part: part || '' };
      if (end) o.end = pad(end);   // שעת הסיום, כשכתובה — שינוי מועד שומר על משך המפגש
      out.push(o);
    }
  };
  const time = String(m.time || '');
  const goal = String(m.goal || '');
  let r;
  if (/בשעה \d/.test(goal)) {
    goal.split(' · ').forEach(seg => {
      const track = seg.split(' (')[0].replace(/^לכל שלוש התוכניות$/, '').trim();
      const re = /(\d{1,2})\.(\d{1,2}) בשעה (\d{1,2}:\d{2})/g;
      while ((r = re.exec(seg))) add(isoOf(r[1], r[2]), r[3], track);
    });
  } else if (/\d{1,2}\.\d{1,2} · \d{1,2}:\d{2}/.test(time)) {
    const re = /(בוקר|ערב|אחה"צ|קבוצה [א-ת]׳)?\s*(\d{1,2})\.(\d{1,2}) · (\d{1,2}:\d{2})(?:\s*[–-]\s*(\d{1,2}:\d{2}))?/g;
    while ((r = re.exec(time))) add(isoOf(r[2], r[3]), r[4], r[1], r[5]);
  } else {
    const re = /(^|[^–\-\d:])(\d{1,2}:\d{2})(?:\s*[–-]\s*(\d{1,2}:\d{2}))?/g;
    while ((r = re.exec(time))) add(m.date, r[2], '', r[3]);
  }
  return out.sort((a, b) => (a.date + a.start).localeCompare(b.date + b.start));
};

