(function roleModal(){
  const wrap = document.createElement('div');
  wrap.className = 'rmodal';
  wrap.setAttribute('role','dialog');
  wrap.setAttribute('aria-modal','true');
  wrap.setAttribute('aria-labelledby','rmTitle');
  wrap.innerHTML =
    '<div class="bd" data-close></div>' +
    '<div class="sheet">' +
      '<div class="top">' +
        '<button class="x" type="button" data-close aria-label="סגירה">✕</button>' +
        '<h2 id="rmTitle"></h2>' +
        '<div class="chips"></div>' +
      '</div>' +
      '<div class="bodyx"></div>' +
    '</div>';
  document.body.appendChild(wrap);

  const elTitle = wrap.querySelector('#rmTitle');
  const elChips = wrap.querySelector('.chips');
  const elBody  = wrap.querySelector('.bodyx');
  const sheet   = wrap.querySelector('.sheet');
  let lastFocus = null;

  const li  = a => '<ul>' + a.map(t => '<li>' + t + '</li>').join('') + '</ul>';

  function render(d){
    elTitle.innerHTML = d.title;
    elChips.innerHTML = (d.chips || []).map((c,i) =>
      '<span class="tag ' + (i === 0 ? 'cyn' : i === 1 ? 'tea' : 'bgr') + '">' + c + '</span>').join('');

    let h = '<p class="lead">' + d.lead + '</p>';
    if (d.note) h += '<p class="note">' + d.note + '</p>';

    (d.sections || []).forEach(s => {
      h += '<h3>' + s.h + '</h3>';
      if (s.items) h += li(s.items);
      if (s.acts)  h += s.acts.map(a => '<div class="act"><b>' + a.b + '</b>' + li(a.items) + '</div>').join('');
    });

    if (d.pending){
      h += '<p class="note">משרד העבודה טרם פרסם מסמך "הגדרת תפקיד" נפרד לתפקיד זה. ' +
           'ההגדרה שלמעלה היא ההגדרה הרשמית מתוך מסמך <b>"בעלי תפקידים מובילים בבית הספר — חלוקת שעות, גמולים ודגשים"</b>. ' +
           'ברגע שתפורסם הגדרה מלאה — היא תתווסף כאן.</p>' +
           '<div class="src"><span class="meta">המקור המחייב: מסמך בעלי התפקידים של מינהל הכשרה מקצועית.</span>' +
           '<a class="btn line" href="baaley-tafkidim.html">למסמך ההנחיות המלא</a></div>';
    } else {
      h += '<div class="src"><span class="meta">' + (d.srcMeta || 'מסמך רשמי · מינהל הכשרה מקצועית, משרד העבודה · תוקף ההנחיות: החל משנת תשפ״ו · עודכן יוני 2026') + '</span>' +
           (function(){
             var loc = d.src.url.indexOf('docs/') === 0;
             return '<a class="btn primary" href="' + d.src.url + '"' +
                    (loc ? ' download>' : ' target="_blank" rel="noopener">') +
                    (d.src.label || 'הגדרת התפקיד המלאה') + (loc ? ' ⬇' : ' ↗') + '</a>';
           })() + '</div>';
    }
    elBody.innerHTML = h;
    elBody.scrollTop = 0;
  }

  function open(id){
    const d = ROLE_DEFS[id];
    if (!d) return;
    lastFocus = document.activeElement;
    render(d);
    wrap.classList.add('on');
    document.body.style.overflow = 'hidden';
    wrap.querySelector('.x').focus();
    if (history.replaceState) history.replaceState(null,'','#' + id);
  }

  function close(){
    wrap.classList.remove('on');
    document.body.style.overflow = '';
    if (lastFocus) lastFocus.focus();
    if (history.replaceState) history.replaceState(null,'',location.pathname + location.search);
  }

  wrap.addEventListener('click', e => { if (e.target.closest('[data-close]')) close(); });
  document.addEventListener('keydown', e => {
    if (!wrap.classList.contains('on')) return;
    if (e.key === 'Escape') { close(); return; }
    if (e.key === 'Tab'){                       // מלכודת פוקוס
      const f = sheet.querySelectorAll('button, a[href]');
      if (!f.length) return;
      const first = f[0], last = f[f.length - 1];
      if (e.shiftKey && document.activeElement === first){ e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last){ e.preventDefault(); first.focus(); }
    }
  });

  document.querySelectorAll('.rolecard').forEach(card => {
    card.addEventListener('click', () => open(card.id));
    card.addEventListener('keydown', e => {
      if (e.key === 'Enter' || e.key === ' '){ e.preventDefault(); open(card.id); }
    });
  });

  /* פתיחה ישירה מקישור עמוק, למשל tafkidim.html#matal */
  const hash = location.hash.replace('#','');
  if (hash && ROLE_DEFS[hash]) setTimeout(() => open(hash), 260);
})();
